create table if not exists public.promo_codes (
  id bigint generated by default as identity primary key, code text not null unique,
  discount_type text not null check (discount_type in ('percent','fixed')), discount_value numeric(12,2) not null check (discount_value > 0),
  min_order_amount numeric(12,2) not null default 0 check (min_order_amount >= 0), usage_limit integer check (usage_limit is null or usage_limit > 0),
  used_count integer not null default 0 check (used_count >= 0), starts_at timestamptz, expires_at timestamptz,
  active boolean not null default true, created_at timestamptz not null default now()
);
create index if not exists idx_promo_codes_active on public.promo_codes (active, code);

