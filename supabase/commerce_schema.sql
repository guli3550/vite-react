create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  description text not null default '',
  price numeric(12,2) not null default 0 check (price >= 0),
  old_price numeric(12,2) check (old_price is null or old_price >= 0),
  image text not null default '', images jsonb not null default '[]'::jsonb,
  sizes jsonb not null default '[]'::jsonb, colors jsonb not null default '[]'::jsonb,
  rating numeric(3,2) not null default 0 check (rating >= 0 and rating <= 5), reviews integer not null default 0 check (reviews >= 0),
  stock integer not null default 0 check (stock >= 0), featured boolean not null default false, active boolean not null default true,
  sort_order integer not null default 0, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
