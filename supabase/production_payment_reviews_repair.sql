-- GULI PRODUCTION PAYMENT + REVIEWS REPAIR
-- Safe/idempotent. Does not delete orders, products, reviews or receipt files.
-- Run this ONE file in the Supabase SQL Editor if manual-card receipts or reviews
-- are not yet installed in production.

begin;

-- Manual HUMO / UZCARD receipt state.
alter table if exists public.orders
  add column if not exists payment_status text not null default 'pending',
  add column if not exists payment_receipt_path text,
  add column if not exists payment_receipt_uploaded_at timestamptz,
  add column if not exists payment_verified_at timestamptz;

alter table if exists public.orders drop constraint if exists orders_payment_status_check;
alter table if exists public.orders add constraint orders_payment_status_check
  check (payment_status in ('pending','receipt_uploaded','verified','rejected'));

create index if not exists orders_payment_status_idx on public.orders(payment_status);
create index if not exists orders_payment_receipt_idx on public.orders(payment_receipt_path) where payment_receipt_path is not null;

insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('payment-receipts','payment-receipts',false,6291456,array['image/jpeg','image/png','image/webp','application/pdf'])
on conflict (id) do update set public=false,file_size_limit=6291456,allowed_mime_types=array['image/jpeg','image/png','image/webp','application/pdf'];

-- Product review table follows the existing public.products.id type.
do $$
declare product_id_type text;
begin
  select format_type(a.atttypid,a.atttypmod) into product_id_type
  from pg_attribute a
  join pg_class c on c.oid=a.attrelid
  join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relname='products' and a.attname='id'
    and a.attnum>0 and not a.attisdropped;

  if product_id_type='uuid' then
    execute $sql$
      create table if not exists public.product_reviews (
        id bigint generated by default as identity primary key,
        product_id uuid not null references public.products(id) on delete cascade,
        product_code text not null,
        telegram_id bigint not null,
        username text,
        first_name text,
        rating integer not null check (rating between 1 and 5),
        comment text not null check (char_length(comment) between 3 and 1200),
        photos jsonb not null default '[]'::jsonb,
        verified_purchase boolean not null default false,
        order_number text not null,
        status text not null default 'approved' check (status in ('approved','hidden')),
        created_at timestamptz not null default now(),
        updated_at timestamptz not null default now(),
        unique(product_id,telegram_id,order_number)
      )
    $sql$;
  elsif product_id_type='bigint' then
    execute $sql$
      create table if not exists public.product_reviews (
        id bigint generated by default as identity primary key,
        product_id bigint not null references public.products(id) on delete cascade,
        product_code text not null,
        telegram_id bigint not null,
        username text,
        first_name text,
        rating integer not null check (rating between 1 and 5),
        comment text not null check (char_length(comment) between 3 and 1200),
        photos jsonb not null default '[]'::jsonb,
        verified_purchase boolean not null default false,
        order_number text not null,
        status text not null default 'approved' check (status in ('approved','hidden')),
        created_at timestamptz not null default now(),
        updated_at timestamptz not null default now(),
        unique(product_id,telegram_id,order_number)
      )
    $sql$;
  else
    raise exception 'Unsupported public.products.id type: %',product_id_type;
  end if;
end $$;

alter table public.product_reviews add column if not exists product_code text;
alter table public.product_reviews add column if not exists username text;
alter table public.product_reviews add column if not exists first_name text;
alter table public.product_reviews add column if not exists rating integer;
alter table public.product_reviews add column if not exists comment text;
alter table public.product_reviews add column if not exists photos jsonb default '[]'::jsonb;
alter table public.product_reviews add column if not exists verified_purchase boolean default false;
alter table public.product_reviews add column if not exists order_number text;
alter table public.product_reviews add column if not exists status text default 'approved';
alter table public.product_reviews add column if not exists created_at timestamptz default now();
alter table public.product_reviews add column if not exists updated_at timestamptz default now();

create index if not exists idx_product_reviews_product_status_created on public.product_reviews(product_id,status,created_at desc);
create index if not exists idx_product_reviews_telegram on public.product_reviews(telegram_id,created_at desc);

alter table public.product_reviews enable row level security;
drop policy if exists product_reviews_public_read on public.product_reviews;
create policy product_reviews_public_read on public.product_reviews for select using (status='approved');

insert into storage.buckets (id,name,public)
values ('review-images','review-images',true)
on conflict (id) do update set public=true;

commit;

select 'GULI payment + reviews repair completed successfully' as result;
