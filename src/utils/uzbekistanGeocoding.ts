export function matchUzbekistanRegionAndDistrict(
  rawState: string,
  rawCounty: string,
  rawCity: string,
  lat: number,
  lon: number,
  rawSuburb = "",
): { region: string; district: string } {
  const combined = `${normalizeGeoToken(rawState)} ${normalizeGeoToken(rawCounty)} ${normalizeGeoToken(rawCity)} ${normalizeGeoToken(rawSuburb)}`;
  const stateNorm = normalizeGeoToken(rawState);
  const countyNorm = normalizeGeoToken(rawCounty);
  const cityNorm = normalizeGeoToken(rawCity);

  let foundRegion = "";

  // Check explicit Tashkent city text or tight city bounds
  if (
    stateNorm === "toshkent" ||
    (cityNorm === "toshkent" && !stateNorm.includes("viloyat")) ||
    (lat >= 41.18 && lat <= 41.40 && lon >= 69.12 && lon <= 69.42)
  ) {
    foundRegion = "Toshkent sh.";
  } else {
    for (const rKey of Object.keys(UZBEKISTAN_REGIONS_DATA)) {
      const nKey = normalizeGeoToken(rKey);
      if (!nKey) continue;
      if (
        combined.includes(nKey) ||
        (nKey.includes("fargona") && (combined.includes("qoqon") || combined.includes("margilon") || combined.includes("yaypan"))) ||
        (nKey.includes("qashqadaryo") && combined.includes("qarshi")) ||
        (nKey.includes("surxondaryo") && combined.includes("termiz")) ||
        (nKey.includes("xorazm") && (combined.includes("urganch") || combined.includes("xiva"))) ||
        (nKey.includes("sirdaryo") && combined.includes("guliston")) ||
        (nKey.includes("qoraqalp") && (combined.includes("nukus") || combined.includes("qoraqalp")))
      ) {
        foundRegion = rKey;
        break;
      }
    }
  }

  // Coordinate bounding box fallback
  if (!foundRegion) {
    if (lat >= 40.5 && lat <= 42.2 && lon >= 68.5 && lon <= 71.2) foundRegion = "Toshkent vil.";
    else if (lat >= 39.1 && lat <= 40.2 && lon >= 65.5 && lon <= 67.5) foundRegion = "Samarqand vil.";
    else if (lat >= 40.0 && lat <= 40.9 && lon >= 70.3 && lon <= 72.0) foundRegion = "Farg‘ona vil.";
    else if (lat >= 40.4 && lat <= 41.0 && lon >= 71.9 && lon <= 73.2) foundRegion = "Andijon vil.";
    else if (lat >= 40.7 && lat <= 41.5 && lon >= 70.4 && lon <= 72.2) foundRegion = "Namangan vil.";
    else if (lat >= 38.8 && lat <= 41.1 && lon >= 62.1 && lon <= 65.2) foundRegion = "Buxoro vil.";
    else if (lat >= 38.2 && lat <= 39.4 && lon >= 64.9 && lon <= 67.5) foundRegion = "Qashqadaryo vil.";
    else if (lat >= 37.1 && lat <= 38.6 && lon >= 66.5 && lon <= 68.4) foundRegion = "Surxondaryo vil.";
    else if (lat >= 41.0 && lat <= 42.0 && lon >= 60.0 && lon <= 61.5) foundRegion = "Xorazm vil.";
    else if (lat >= 39.8 && lat <= 43.5 && lon >= 62.0 && lon <= 66.0) foundRegion = "Navoiy vil.";
    else if (lat >= 39.8 && lat <= 41.5 && lon >= 67.0 && lon <= 68.9) foundRegion = "Jizzax vil.";
    else if (lat >= 40.0 && lat <= 41.0 && lon >= 68.3 && lon <= 69.3) foundRegion = "Sirdaryo vil.";
    else if (lat >= 41.0 && lat <= 45.6 && lon >= 56.0 && lon <= 62.5) foundRegion = "Qoraqalpog‘iston Respublikasi";
    else foundRegion = "Toshkent sh.";
  }

  const distList = UZBEKISTAN_REGIONS_DATA[foundRegion] || [];
  let foundDistrict = "";

  if (foundRegion === "Farg‘ona vil.") {
    if (combined.includes("qoqon")) {
      foundDistrict = "Qo‘qon sh.";
    } else if (combined.includes("yaypan") || combined.includes("ozbekiston")) {
      foundDistrict = "O‘zbekiston tumani";
    }
  }

  if (!foundDistrict) {
    for (const d of distList) {
      const nD = normalizeGeoToken(d);
      if (!nD) continue;
      if (d === "O‘zbekiston tumani") continue;

      const synonyms = DISTRICT_SYNONYMS[d] || [];
      const matchesSynonym = synonyms.some((syn) => {
        const ns = normalizeGeoToken(syn);
        return Boolean(ns) && combined.includes(ns);
      });

      if (
        matchesSynonym ||
        combined.includes(nD) ||
        (countyNorm && (nD.includes(countyNorm) || countyNorm.includes(nD))) ||
        (cityNorm && (nD.includes(cityNorm) || cityNorm.includes(nD)))
      ) {
        foundDistrict = d;
        break;
      }
    }
  }

  if (!foundDistrict && foundRegion === "Farg‘ona vil.") {
    if (lat >= 40.48 && lat <= 40.58 && lon >= 70.87 && lon <= 71.02) {
      foundDistrict = "Qo‘qon sh.";
    } else if (lat >= 40.25 && lat <= 40.58 && lon >= 70.70 && lon <= 71.15) {
      foundDistrict = "O‘zbekiston tumani";
    }
  }

  if (!foundDistrict && foundRegion === "Toshkent sh.") {
    if (lat <= 41.285 && lon <= 69.235) foundDistrict = "Chilonzor tumani";
    else if (lat >= 41.32 && lon >= 69.25 && lon <= 69.32) foundDistrict = "Yunusobod tumani";
    else if (lat >= 41.30 && lon >= 69.32) foundDistrict = "Mirzo Ulug‘bek tumani";
    else if (lat <= 41.285 && lon >= 69.285) foundDistrict = "Yashnobod tumani";
    else if (lat <= 41.235 && lon <= 69.24) foundDistrict = "Sergeli tumani";
    else if (lat >= 41.29 && lon <= 69.205) foundDistrict = "Uchtepa tumani";
    else if (lat >= 41.285 && lat <= 41.31 && lon >= 69.255 && lon <= 69.30) foundDistrict = "Mirobod tumani";
    else if (lat >= 41.31 && lon >= 69.22 && lon <= 69.255) foundDistrict = "Shayxontohur tumani";
    else if (lat >= 41.335 && lon <= 69.25) foundDistrict = "Olmazor tumani";
    else foundDistrict = "Yakkasaroy tumani";
  }

  if (!foundDistrict && distList.length > 0) {
    foundDistrict = distList[0];
  }

  return { region: foundRegion, district: foundDistrict };
}

function cleanStreetText(raw: string): string {
  const lat = transliterateCyrillicToUzbekLatin(raw || "");
  return lat
    .replace(/\b(ulitsa|ul\.|prospekt|pr\.|pereulok|per\.|ko'chasi|kochasi)\b/gi, (m) => {
      if (/ko'?chasi/i.test(m)) return "ko‘chasi";
      return "";
    })
    .replace(/\s+/g, " ")
    .replace(/^[,.\s]+|[,.\s]+$/g, "")
    .trim();
}

function cleanHouseText(raw: string): string {
  const lat = transliterateCyrillicToUzbekLatin(raw || "");
  return lat
    .replace(/^(dom|d\.|uy|№|#)\s*/i, "")
    .replace(/\s+/g, " ")
    .trim();
}

export function formatResolvedAddressLine(parts: {
  region: string;
  district: string;
  street: string;
  house: string;
}): string {
  const segments = [
    parts.region?.trim(),
    parts.district?.trim(),
    parts.street?.trim(),
    parts.house?.trim() ? `${parts.house.trim()}-uy` : "",
  ].filter(Boolean);
  return segments.join(", ");
}

export function extractExactCheckoutAddress(
  addr: Record<string, any> | null | undefined,
  lat: number,
  lon: number,
  source: ResolvedCheckoutAddress["source"] = "nominatim",
): ResolvedCheckoutAddress {
  const safeAddr = addr || {};
  const rawState = String(safeAddr.state || safeAddr.region || safeAddr.principalSubdivision || "");
  const rawCounty = String(
    safeAddr.county ||
      safeAddr.district ||
      safeAddr.city_district ||
      safeAddr.municipality ||
      safeAddr.borough ||
      "",
  );
  const rawCity = String(safeAddr.city || safeAddr.town || safeAddr.village || "");
  const rawSuburb = String(
    safeAddr.suburb || safeAddr.neighbourhood || safeAddr.quarter || safeAddr.residential || "",
  );

  const { region, district } = matchUzbekistanRegionAndDistrict(
    rawState,
    rawCounty,
    rawCity,
    lat,
    lon,
    rawSuburb,
  );

  const roadCandidate = cleanStreetText(
    String(
      safeAddr.road ||
        safeAddr.street ||
        safeAddr.pedestrian ||
        safeAddr.footway ||
        safeAddr.residential ||
        "",
    ),
  );
  const neighborhoodCandidate = cleanStreetText(
    String(
      safeAddr.neighbourhood ||
        safeAddr.quarter ||
        safeAddr.suburb ||
        safeAddr.hamlet ||
        safeAddr.village ||
        safeAddr.amenity ||
        safeAddr.building ||
        "",
    ),
  );

  let street = roadCandidate;
  if (
    neighborhoodCandidate &&
    normalizeGeoToken(neighborhoodCandidate) !== normalizeGeoToken(district) &&
    normalizeGeoToken(neighborhoodCandidate) !== normalizeGeoToken(region)
  ) {
    if (!street) {
      street = neighborhoodCandidate;
    } else if (!street.toLowerCase().includes(neighborhoodCandidate.toLowerCase()) && /\d/.test(neighborhoodCandidate)) {
      street = `${neighborhoodCandidate}, ${street}`;
    }
  }

  const house = cleanHouseText(
    String(safeAddr.house_number || safeAddr.housenumber || safeAddr.house || ""),
  );

  const formattedAddress = formatResolvedAddressLine({ region, district, street, house });

  return {
    latitude: lat,
    longitude: lon,
    region,
    district,
    street,
    house,
    formattedAddress,
    source,
  };
}

export async function reverseGeocodeCoordinates(
  lat: number,
  lon: number,
  signal?: AbortSignal,
): Promise<ResolvedCheckoutAddress> {
  // 1. Primary: Nominatim (high building/house_number precision in Uzbekistan)
  try {
    const res = await fetch(
      `https://nominatim.openstreetmap.org/reverse?format=json&lat=${lat}&lon=${lon}&zoom=18&addressdetails=1&accept-language=uz,ru,en`,
      { signal },
    );
    if (res.ok) {
      const data = await res.json();
      if (data?.address) {
        return extractExactCheckoutAddress(data.address, lat, lon, "nominatim");
      }
    }
  } catch (err) {
    if ((err as Error)?.name === "AbortError") throw err;
  }

  // 2. Fallback: Photon Komoot (OSM-based without strict client quota limits)
  try {
    const res = await fetch(
      `https://photon.komoot.io/reverse?lat=${lat}&lon=${lon}`,
      { signal },
    );
    if (res.ok) {
      const data = await res.json();
      const props = data?.features?.[0]?.properties;
      if (props) {
        return extractExactCheckoutAddress(
          {
            state: props.state,
            county: props.county,
            city: props.city,
            district: props.district,
            suburb: props.locality,
            road: props.street || props.name,
            house_number: props.housenumber,
          },
          lat,
          lon,
          "photon",
        );
      }
    }
  } catch (err) {
    if ((err as Error)?.name === "AbortError") throw err;
  }

  // 3. Coordinate-based fallback
  return extractExactCheckoutAddress({}, lat, lon, "fallback");
}

export async function searchUzbekistanAddresses(
  query: string,
  biasLat?: number,
  biasLon?: number,
  signal?: AbortSignal,
): Promise<AddressSearchCandidate[]> {
  const clean = query.trim();
  if (clean.length < 2) return [];

  try {
    const biasParams =
      biasLat && biasLon ? `&lat=${biasLat}&lon=${biasLon}` : "&lat=41.2995&lon=69.2401";
    const url = `https://photon.komoot.io/api/?q=${encodeURIComponent(clean)}&limit=6&bbox=55.9,37.1,73.2,45.6${biasParams}`;
    const res = await fetch(url, { signal });
    if (res.ok) {
      const json = await res.json();
      const features = Array.isArray(json?.features) ? json.features : [];
      if (features.length > 0) {
        return features
          .map((f: any, idx: number) => {
            const coords = f?.geometry?.coordinates || [];
            const lon = Number(coords[0]);
            const lat = Number(coords[1]);
            const p = f?.properties || {};
            if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;

            const resolved = extractExactCheckoutAddress(
              {
                state: p.state,
                county: p.county,
                city: p.city,
                district: p.district,
                suburb: p.locality,
                road: p.street || p.name,
                house_number: p.housenumber,
              },
              lat,
              lon,
              "photon",
            );

            const title =
              [resolved.street || cleanStreetText(String(p.name || "")), resolved.house ? `${resolved.house}-uy` : ""]
                .filter(Boolean)
                .join(", ") || resolved.district;

            return {
              id: `ph-${idx}-${lat.toFixed(5)}-${lon.toFixed(5)}`,
              title,
              subtitle: `${resolved.region}, ${resolved.district}`,
              region: resolved.region,
              district: resolved.district,
              street: resolved.street,
              house: resolved.house,
              latitude: lat,
              longitude: lon,
            } as AddressSearchCandidate;
          })
          .filter(Boolean) as AddressSearchCandidate[];
      }
    }
  } catch (err) {
    if ((err as Error)?.name === "AbortError") throw err;
  }

  // Fallback to Nominatim search in Uzbekistan
  try {
    const res = await fetch(
      `https://nominatim.openstreetmap.org/search?format=json&addressdetails=1&countrycodes=uz&limit=6&accept-language=uz,ru,en&q=${encodeURIComponent(clean)}`,
      { signal },
    );
    if (res.ok) {
      const rows = await res.json();
      if (Array.isArray(rows)) {
        return rows
          .map((r: any, idx: number) => {
            const lat = Number(r?.lat);
            const lon = Number(r?.lon);
            if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;
            const resolved = extractExactCheckoutAddress(r.address, lat, lon, "nominatim");
            const title =
              [resolved.street, resolved.house ? `${resolved.house}-uy` : ""]
                .filter(Boolean)
                .join(", ") || resolved.district;
            return {
              id: `nm-${idx}-${lat.toFixed(5)}-${lon.toFixed(5)}`,
              title,
              subtitle: `${resolved.region}, ${resolved.district}`,
              region: resolved.region,
              district: resolved.district,
              street: resolved.street,
              house: resolved.house,
              latitude: lat,
              longitude: lon,
            } as AddressSearchCandidate;
          })
          .filter(Boolean) as AddressSearchCandidate[];
      }
    }
  } catch (err) {
    if ((err as Error)?.name === "AbortError") throw err;
  }

  return [];
}
