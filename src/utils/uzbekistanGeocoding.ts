export function transliterateCyrillicToUzbekLatin(input: string): string {
  if (!input) return "";
  let out = "";
  for (let i = 0; i < input.length; i++) {
    const ch = input[i];
    out += CYR_TO_LAT[ch] ?? ch;
  }
  return out
    .replace(/\bul\.\s*/gi, "")
    .replace(/\bulitsa\s+/gi, "")
    .replace(/\bprospekt\s+/gi, "")
    .replace(/\bpr\.\s*/gi, "")
    .replace(/\s+/g, " ")
    .trim();
}

function normalizeGeoToken(s: string): string {
  const lat = transliterateCyrillicToUzbekLatin(s || "");
  return lat
    .toLowerCase()
    .replace(/['`‘’ʼ]/g, "")
    .replace(/tashkent/g, "toshkent")
    .replace(/samarkand/g, "samarqand")
    .replace(/bukhara/g, "buxoro")
    .replace(/fergana/g, "fargona")
    .replace(/andijan/g, "andijon")
    .replace(/kashkadarya/g, "qashqadaryo")
    .replace(/surkhandarya/g, "surxondaryo")
    .replace(/khorezm/g, "xorazm")
    .replace(/karakalpak/g, "qoraqalpogiston")
    .replace(/jizzakh/g, "jizzax")
    .replace(/syrdarya/g, "sirdaryo")
    .replace(/chilanzar/g, "chilonzor")
    .replace(/yunusabad/g, "yunusobod")
    .replace(/almazar/g, "olmazor")
    .replace(/mirabad/g, "mirobod")
    .replace(/yashnabad/g, "yashnobod")
    .replace(/yakasaray|yakkasaray/g, "yakkasaroy")
    .replace(/shaikhantahur|shaykhontohur/g, "shayxontohur")
    .replace(/kokand|qoqon|kokand/g, "qoqon")
    .replace(/margilan/g, "margilon")
    .replace(/karshi/g, "qarshi")
    .replace(/termez/g, "termiz")
    .replace(/urgench/g, "urganch")
    .replace(/khiva/g, "xiva")
    .replace(/skiy\b|skaya\b|skoye\b|skiy rayon/g, "")
    .replace(/rayon|oblast|gorod|viloyat(i)?|vil\.?|tuman(i)?|tum\.?|shahar(i)?|sh\.?/g, "")
    .replace(/district|region|city|state|county|area|republic|respublikasi|resp/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

